'''
二、第一个陷阱：程序里的字符串是「反着存」的
程序在运行时，会通过几条 movabs（把一串立即数直接塞进寄存器）来拼出关键字符串。但这里有个坑——x86 是小端序，8 字节的立即数在内存里是倒着放的。
那条指令塞进去的数是 0x534C43444E，如果按人眼从左到右读会看成 SLCDN；但内存里实际字节顺序是 NDCLS。
另一条塞的是 0x776F646168，肉眼看像 wodah，内存里其实是 adow。
所以程序拼出来的两个字符串是：
密钥 key = "ADSFK"（早先写好的）＋ "NDCLS"（上面反读得到） = ADSFKNDCLS
目标文本 text = "kills" ＋ "adow" = killshadow
这个 killshadow 就是程序最终要拿去和你输入比对的那串「正确答案」。
额外提醒：程序还给一个小写版本的 key 表留了位置，但那段内存从头到尾没被写过（全是 0），真正参与运算的就是上面那个大写密钥。

三、输入的变换规则（这步是核心）
程序把你输入的每一个字符，按下面的规则变成另一个字符：
新字符 = （原字符 − 0x27 − 密钥[r] ＋ 0x61）对 26 取模后 ＋ 0x61
r 是当前字符的位置序号，每 10 个一循环（密钥只有 10 个字母，长度不够就轮着用）。
0x27、0x61 这些是 ASCII 码的固定偏移（0x61 是字母 a 的码），本质就是把字符映射到 0~25 的「字母序号」上做运算。
密钥[r] 用的是上面那个 ADSFKNDCLS 对应位置字母的值（比如第一个位置取 A=65）。
整个式子其实是一个带密钥的凯撒/维吉尼亚式移位：把输入字母按密钥逐位「往后挪」若干格，再绕回字母表头尾。
变换只针对字母（A–Z、a–z），其它字符（比如空格）会被跳过并留下空洞，所以一个能匹配上的合法输入必须是恰好 10 个字母——而且题目 intended 的解全部走大写分支。

四、因为我们知道「答案」，所以反过来推「输入」
正常程序是：输入 → 变换 → 和 killshadow 比。
但我们手里有 killshadow（目标），手里也有密钥 ADSFKNDCLS，所以反着算：对 killshadow 的每一位，去试「哪个输入字母经过变换后会变成它」。
具体做法：目标有 10 个字符，每个位置都在 A–Z 这 26 个可能里逐个试，套上面的公式看哪个能算出当前的目标字符，找到了就记下来。10 个位置试完，得到输入字母串：
KLDQCUDFZO
'''
KEY    = b"adsfkndcls"
TARGET = b"killshadow"

flag = ""
for i, oc in enumerate(TARGET):
    for v in range(0x41, 0x5b):          # 逐位枚举 'A'..'Z'
        if (v - 0x27 - KEY[i % 10] + 0x61) % 26 + 0x61 == oc:
            flag += chr(v)
            break

print(f"flag{{{flag}}}")
